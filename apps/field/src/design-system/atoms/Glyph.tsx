export type GlyphName = keyof typeof drawings;

export type GlyphProps = {
  name: GlyphName;
  /** Drawn at its Figma size unless a width is given; height follows the aspect ratio. */
  width?: number;
  color?: ColorToken;
  /** Omit for decoration. */
  accessibilityLabel?: string;
};

// Renders one Figma glyph in a token colour.
export function Glyph({ name, width, color = 'white', accessibilityLabel }: GlyphProps) {
  const drawing: Drawing = drawings[name];
  const drawnWidth = width ?? drawing.width;
  const drawnHeight = (drawnWidth / drawing.width) * drawing.height;
  const decorative = accessibilityLabel === undefined;
  return (
    <Svg
      width={drawnWidth}
      height={drawnHeight}
      viewBox={`0 0 ${drawing.width} ${drawing.height}`}
      fill="none"
      accessibilityRole={decorative ? 'none' : 'image'}
      accessibilityLabel={accessibilityLabel}
      accessibilityElementsHidden={decorative}
      importantForAccessibility={decorative ? 'no-hide-descendants' : 'yes'}
    >
      {drawing.draw(colors[color])}
    </Svg>
  );
}
