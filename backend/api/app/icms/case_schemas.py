class CaseQuery(CollectionParams):
    status: list[str] | None = Field(
        default=None, description=f"Repeatable. One of: {', '.join(STATUSES)}")
    stage_no: list[int] | None = Field(default=None, description="Repeatable, 1-7.")
    zone_cd: list[ZoneCode] | None = Field(default=None, description="Repeatable.")
    complaint_type_cd: list[Code] | None = Field(default=None, description="Repeatable.")
    source: list[str] | None = Field(default=None, description="Repeatable.")
    assignee_user_id: list[UserId] | None = Field(
        default=None, description="Repeatable. Matches the OPEN survey assignment only.")
    priority: list[str] | None = Field(
        default=None, description=f"Repeatable. One of: {', '.join(PRIORITIES)}")
    ulpin: list[str] | None = Field(default=None, description="Repeatable. Exact match.")
    khasra_no: list[str] | None = Field(default=None, description="Repeatable. Exact match.")
    village_lgd_code: list[str] | None = Field(default=None, description="Repeatable.")
    mine: bool = Field(
        default=False,
        description="Only cases whose open survey assignment is the caller's. "
                    "This is what the field app sends.",
    )
    filed_from: date | None = Field(default=None, description="Inclusive, on the filed date.")
    filed_to: date | None = Field(default=None, description="Inclusive, on the filed date.")

    @model_validator(mode="after")
    def _known_vocabulary(self) -> CaseQuery:
        for value in self.status or ():
            if value not in STATUSES:
                raise ValueError(f"unknown status '{value}'; one of: {', '.join(STATUSES)}")
        for value in self.source or ():
            if value not in SOURCES:
                raise ValueError(f"unknown source '{value}'; one of: {', '.join(SOURCES)}")
        for value in self.priority or ():
            if value not in PRIORITIES:
                raise ValueError(
                    f"unknown priority '{value}'; one of: {', '.join(PRIORITIES)}")
        for value in self.stage_no or ():
            if not 1 <= value <= 7:
                raise ValueError("stage_no is between 1 and 7")
        if self.filed_from and self.filed_to and self.filed_from > self.filed_to:
            raise ValueError("filed_from must not be after filed_to")
        return self


class CaseRow(BaseModel):
    model_config = ConfigDict(from_attributes=True)

    case_ref: str
    zone_cd: str
    zone_name: str
    property_address: str | None = None
    landmark: str | None = None
    complainant_name: str | None = None
    complaint_type_cd: str | None = None
    complaint_type_label: str | None = None
    other_type: str | None = None
    measured_area_sqm: float | None = None
    priority: str | None = None
    ulpin: str | None = None
    khasra_no: str | None = None
    village_lgd_code: str | None = None
    status: str
    stage_no: int
    current_round: int
    source: str
    assignee_user_id: str | None = None
    raised_at: IstDateTime

    @computed_field
    @property
    def parcel_id(self) -> str | None:
        if self.ulpin:
            return self.ulpin
        if self.khasra_no:
            return (f"{self.village_lgd_code}/{self.khasra_no}"
                    if self.village_lgd_code else self.khasra_no)
        return None


