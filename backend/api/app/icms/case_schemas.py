SOURCES = ("detection", "public", "field", "office")
STATUSES = tuple(str(s) for s in Status)
PRIORITIES = CASE_PRIORITIES


class CaseLocation(BaseModel):
    model_config = ConfigDict(extra="forbid")

    latitude: Latitude
    longitude: Longitude


class CaseCreate(BaseModel):
    model_config = ConfigDict(extra="forbid")

    source: str = Field(description=f"One of: {', '.join(SOURCES)}")
    zone_cd: ZoneCode | None = None
    location: CaseLocation | None = None

    detection_id: int | None = Field(
        default=None,
        description="The change polygon this case came from, when source is 'detection'.",
    )

    complaint_type_cd: Code | None = None
    other_type: SafeText | None = None
    detail: SafeLongText | None = None

    complainant_name: Name | None = None
    complainant_phone: PhoneIN | None = None
    complainant_email: Email | None = None

    owner_name: Name | None = None
    owner_phone: PhoneIN | None = None

    property_address: SafeText | None = None
    landmark: PlaceName | None = None
    police_station: PlaceName | None = None
    pin_code: PinCode | None = None
    district: PlaceName | None = None
    state: PlaceName | None = None
    country: PlaceName | None = "India"
    property_type_cd: Code | None = None
    floor_count: int | None = Field(default=None, ge=0, le=200)

    ulpin: ULPIN | None = Field(default=None, description="Bhu-Aadhaar, 14 characters.")
    khasra_no: KhasraNo | None = None
    village_lgd_code: LGDCode | None = None
    district_lgd_code: LGDCode | None = None
    priority: Literal[PRIORITIES] | None = None  # type: ignore[valid-type]

    idempotency_key: IdempotencyKey | None = Field(
        default=None,
        description="Generated by the client at user-action time, not at send time. "
                    "A replay returns the case the first attempt created rather than "
                    "filing the complaint twice.",
    )

    @model_validator(mode="after")
    def _locatable_and_coherent(self) -> CaseCreate:
        if self.source not in SOURCES:
            raise ValueError(f"source must be one of: {', '.join(SOURCES)}")
        if self.zone_cd is None and self.location is None:
            raise ValueError(
                "give either zone_cd or location; the zone is resolved from the "
                "location when one is supplied"
            )
        if self.source == "detection" and self.detection_id is None:
            raise ValueError("source 'detection' requires detection_id")
        if self.source != "detection" and self.detection_id is not None:
            raise ValueError("detection_id is only meaningful when source is 'detection'")
        if self.complaint_type_cd == "other" and not self.other_type:
            raise ValueError("complaint_type_cd 'other' requires other_type")
        return self


